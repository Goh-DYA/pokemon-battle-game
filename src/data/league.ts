export function instantiateBossTeam(trainer: Trainer): ActivePokemon[] {
  return trainer.team.map(template => {
    // scaled for high-level bosses
    const maxHpScaled = template.hp * 2 + 110;
    return {
      name: template.name,
      types: template.types,
      maxHp: maxHpScaled,
      hp: maxHpScaled,
      attack: template.attack,
      defense: template.defense,
      spAttack: template.spAttack,
      spDefense: template.spDefense,
      speed: template.speed,
      moves: template.moves.map(m => getMoveInstance(m)),
      spriteUrl: template.spriteUrl,
      colorTheme: template.colorTheme,
      status: 'Healthy',
      statStages: {
        attack: 0,
        defense: 0,
        spAttack: 0,
        spDefense: 0,
        speed: 0,
      },
    };
  });
}
