export function getPokemonSpriteUrls(name: string) {
  const id = getPokemonId(name);
  return {
    front: `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/${id}.png`,
    back: `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/back/${id}.png`,
    frontAnimated: `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/showdown/${id}.gif`,
    backAnimated: `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/showdown/back/${id}.gif`,
    artwork: `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/official-artwork/${id}.png`
  };
}

export function createActivePokemon(name: string): ActivePokemon {
  const template = POKEMON_DATABASE[name];
  if (!template) {
    throw new Error(`Pokemon template for ${name} not found.`);
  }

  // Double HP conceptually just to make combat highly engaging and allow setups without quick 1-hit faints!
  const multiplier = 4; // Pokémon battle HP scaling factor for standard level 100 (e.g. template * 2 + 110)
  const maxHpScaled = template.hp * 2 + 110;

  const sprites = getPokemonSpriteUrls(template.name);

  return {
    name: template.name,
    types: template.types,
    maxHp: maxHpScaled,
    hp: maxHpScaled,
    attack: template.attack,
    defense: template.defense,
    spAttack: template.spAttack,
    spDefense: template.spDefense,
    speed: template.speed,
    moves: template.moves.map(m => getMoveInstance(m)),
    spriteUrl: template.spriteUrl || sprites.frontAnimated,
    colorTheme: template.colorTheme,
    status: 'Healthy',
    statStages: {
      attack: 0,
      defense: 0,
      spAttack: 0,
      spDefense: 0,
      speed: 0,
    },
  };
}
