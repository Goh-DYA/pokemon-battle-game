// Instantiates a move with standard PP
export function getMoveInstance(name: string): Move {
  const base = MOVES_DATABASE[name];
  if (!base) {
    // Fail-safe to standard Body Slam
    return {
      name,
      type: 'Normal',
      category: 'Physical',
      power: 60,
      accuracy: 100,
      pp: 20,
      maxPp: 20,
      description: 'A basic physical strike.',
    };
  }
  return {
    ...base,
    pp: base.maxPp,
  };
}
